/// A report ready to export: summary figures plus detail sheets.
class Report {
  Report({
    required this.title,
    required this.from,
    required this.to,
    this.summary = const [],
    required this.sheets,
  });

  final String title;
  final DateTime from;
  final DateTime to;
  final List<(String, Object?)> summary;
  final List<XlsxSheet> sheets;

  int get rowCount => sheets.fold(0, (s, x) => s + x.rows.length);
}

class ReportDef {
  const ReportDef({
    required this.id,
    required this.title,
    required this.description,
    required this.roles,
    required this.build,
    this.usesPeriod = true,
  });

  final String id;
  final String title;
  final String description;
  final Set<UserRole> roles;

  /// False for snapshots (e.g. stock on hand, unpaid bills) where the dates
  /// only affect part of the report.
  final bool usesPeriod;
  final Report Function(HospitalStore s, DateTime from, DateTime to) build;
}

/// The workbook for [r]: a Summary sheet first, then the detail sheets.
Uint8List reportXlsx(
  Report r, {
  required String hospital,
  required String generatedBy,
}) => buildXlsx([
  XlsxSheet(
    name: 'Summary',
    headers: ['Item', 'Value'],
    widths: [34, 40],
    rows: [
      ['Report', r.title],
      ['Hospital', hospital],
      ['Period from', DateTime(r.from.year, r.from.month, r.from.day)],
      ['Period to', DateTime(r.to.year, r.to.month, r.to.day, 23, 59)],
      ['Generated', DateTime.now()],
      ['Generated by', generatedBy],
      for (final (k, v) in r.summary) [k, v],
    ],
  ),
  ...r.sheets,
]);

String reportFileName(Report r) {
  String d(DateTime x) =>
      '${x.year}${x.month.toString().padLeft(2, '0')}${x.day.toString().padLeft(2, '0')}';
  final slug = r.title.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]+'), '-');
  return '$slug-${d(r.from)}-${d(r.to)}';
}

bool _inRange(DateTime d, DateTime from, DateTime to) =>
    !d.isBefore(DateTime(from.year, from.month, from.day)) &&
    d.isBefore(DateTime(to.year, to.month, to.day + 1));

double _sum<T>(Iterable<T> xs, num Function(T) f) =>
    xs.fold(0.0, (a, x) => a + f(x));

String? _doctorOf(HospitalStore s, Invoice inv) => inv.consultationId != null
    ? s.consultationById(inv.consultationId!)?.doctorId
    : inv.admissionId != null
    ? s.admissionById(inv.admissionId!)?.doctorId
    : inv.surgeryId != null
    ? s.surgeryById(inv.surgeryId!)?.surgeonId
    : null;

