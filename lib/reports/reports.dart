    title: 'Admissions and bed use',
    description: 'Admissions in the period, length of stay and room charges',
    roles: {
      ..._finance,
      UserRole.receptionist,
      UserRole.doctor,
      UserRole.nurse,
    },
    build: (s, from, to) {
      final end = DateTime(to.year, to.month, to.day + 1);
      final list =
          s.admissions
              .where(
                (a) =>
                    a.admittedAt.isBefore(end) &&
                    (a.dischargedAt == null ||
                        !a.dischargedAt!.isBefore(
                          DateTime(from.year, from.month, from.day),
                        )),
              )
              .toList()
            ..sort((a, b) => a.admittedAt.compareTo(b.admittedAt));
      final now = DateTime.now();
      final discharged = list.where((a) => !a.isActive).toList();
      final avgLos = discharged.isEmpty
          ? null
          : (_sum(discharged, (a) => a.totalDays(a.dischargedAt!)) /
                        discharged.length *
                        10)
                    .round() /
                10;
      return Report(
        title: 'Admissions and bed use',
        from: from,
        to: to,
        summary: [
          ('Admissions in or overlapping the period', list.length),
          (
            'Admitted in the period',
            list.where((a) => _inRange(a.admittedAt, from, to)).length,
          ),
          ('Discharged', discharged.length),
          ('Average length of stay (days)', avgLos),
          ('Beds', s.totalBeds),
          ('Currently occupied', s.activeAdmissions.length),
        ],
        sheets: [
          XlsxSheet(
            name: 'Admissions',
            headers: [
              'Admitted',
              'Discharged',
              'Patient',
              'MRN',
              'Doctor',
              'Reason',
              'Rooms',
              'Days',
              'Room charges',
              'Surgeries',
            ],
            rows: [
              for (final a in list)
                [
                  a.admittedAt,
                  a.dischargedAt,
                  s.patientName(a.patientId),
                  s.patientById(a.patientId)?.mrn,
                  s.userName(a.doctorId),
                  a.reason,
                  a.stays.map((x) => x.roomName).join(' > '),
                  a.totalDays(a.dischargedAt ?? now),
                  Money(a.roomCharges(a.dischargedAt ?? now)),
                  s.surgeries
                      .where(
                        (x) =>
                            x.admissionId == a.id &&
                            x.status == SurgeryStatus.completed,
                      )
                      .map((x) => x.procedure)
                      .join(', '),
                ],
            ],
          ),
        ],
      );
    },
