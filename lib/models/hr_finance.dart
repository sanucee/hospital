/// Money received against an invoice. Kept as separate records (rather than
/// only a running total) so collections can be reported by date and method.
class Payment {
  Payment({
    required this.id,
    required this.invoiceId,
    required this.patientId,
    required this.amount,
    required this.method,
    required this.receivedAt,
    this.receivedBy,
    this.claimId,
  });

  final String id;
  final String invoiceId;
  final String patientId;
  final double amount;
  final String method;
  final DateTime receivedAt;
  final String? receivedBy;

  /// Set when the money came from an insurer settling this claim.
  final String? claimId;

  bool get fromInsurer => claimId != null;

  Map<String, dynamic> toJson() => {
    'id': id,
    'invoiceId': invoiceId,
    'patientId': patientId,
    'amount': amount,
    'method': method,
    'receivedAt': receivedAt.toIso8601String(),
    'receivedBy': receivedBy,
    'claimId': claimId,
  };

  factory Payment.fromJson(Map<String, dynamic> j) => Payment(
    id: j['id'],
    invoiceId: j['invoiceId'],
    patientId: j['patientId'] ?? '',
    amount: (j['amount'] as num).toDouble(),
    method: j['method'] ?? 'Cash',
    receivedAt: DateTime.parse(j['receivedAt']),
    receivedBy: j['receivedBy'],
    claimId: j['claimId'],
  );
}

DateTime _dayOnly(DateTime d) => DateTime(d.year, d.month, d.day);
