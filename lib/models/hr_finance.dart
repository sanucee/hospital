enum LeaveStatus { pending, approved, rejected }

class LeaveRequest {
  LeaveRequest({
    required this.id,
    required this.staffId,
    required this.type,
    required this.from,
    required this.to,
    this.reason = '',
    this.status = LeaveStatus.pending,
    required this.requestedAt,
    this.decidedBy,
  });

  final String id;
  final String staffId;
  final LeaveType type;

  /// Inclusive dates (time of day ignored).
  final DateTime from;
  final DateTime to;
  final String reason;
  LeaveStatus status;
  final DateTime requestedAt;
  String? decidedBy;

  int get days => _dayOnly(to).difference(_dayOnly(from)).inDays + 1;

  /// Number of leave days falling in [month] (any day in that month).
  int daysIn(DateTime month) {
    final start = DateTime(month.year, month.month);
    final end = DateTime(month.year, month.month + 1, 0);
    final a = _dayOnly(from).isAfter(start) ? _dayOnly(from) : start;
    final b = _dayOnly(to).isBefore(end) ? _dayOnly(to) : end;
    return b.isBefore(a) ? 0 : b.difference(a).inDays + 1;
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'staffId': staffId,
    'type': type.name,
    'from': from.toIso8601String(),
    'to': to.toIso8601String(),
    'reason': reason,
    'status': status.name,
    'requestedAt': requestedAt.toIso8601String(),
    'decidedBy': decidedBy,
  };

  factory LeaveRequest.fromJson(Map<String, dynamic> j) => LeaveRequest(
    id: j['id'],
    staffId: j['staffId'],
    type: _enumByName(LeaveType.values, j['type'], LeaveType.annual),
    from: DateTime.parse(j['from']),
    to: DateTime.parse(j['to']),
    reason: j['reason'] ?? '',
    status: _enumByName(LeaveStatus.values, j['status'], LeaveStatus.pending),
    requestedAt: DateTime.parse(j['requestedAt']),
    decidedBy: j['decidedBy'],
  );
}

