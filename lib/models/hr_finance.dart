/// A staff member's monthly pay. Stored apart from [StaffUser] so that only
/// administrators and accounts can read salaries.
class SalaryStructure {
  SalaryStructure({
    required this.staffId,
    this.basic = 0,
    this.allowances = 0,
    this.deductions = 0,
    this.bankAccount = '',
  });

  /// Also the record id: one structure per staff member.
  final String staffId;
  double basic;

  /// Housing, transport, call duty... as one monthly amount.
  double allowances;

  /// Tax, pension, loans... as one monthly amount.
  double deductions;
  String bankAccount;

  double get gross => basic + allowances;
  double get net => gross - deductions;

  Map<String, dynamic> toJson() => {
    'id': staffId,
    'staffId': staffId,
    'basic': basic,
    'allowances': allowances,
    'deductions': deductions,
    'bankAccount': bankAccount,
  };

  factory SalaryStructure.fromJson(Map<String, dynamic> j) => SalaryStructure(
    staffId: j['staffId'] ?? j['id'],
    basic: (j['basic'] as num?)?.toDouble() ?? 0,
    allowances: (j['allowances'] as num?)?.toDouble() ?? 0,
    deductions: (j['deductions'] as num?)?.toDouble() ?? 0,
    bankAccount: j['bankAccount'] ?? '',
  );
}

enum PayslipStatus { draft, paid }

/// One staff member's pay for one month, generated by a payroll run.
class Payslip {
  Payslip({
    required this.id,
    required this.staffId,
    required this.month,
    required this.basic,
    required this.allowances,
    required this.deductions,
    this.unpaidLeaveDays = 0,
    this.leaveDeduction = 0,
    this.status = PayslipStatus.draft,
    this.paidAt,
    this.paymentMethod = '',
  });

  final String id;
  final String staffId;

  /// First day of the month this payslip covers.
  final DateTime month;
  final double basic;
  final double allowances;
  final double deductions;
  final int unpaidLeaveDays;
  final double leaveDeduction;
  PayslipStatus status;
  DateTime? paidAt;
  String paymentMethod;

  double get gross => basic + allowances;
  double get net => gross - deductions - leaveDeduction;

  Map<String, dynamic> toJson() => {
    'id': id,
    'staffId': staffId,
    'month': month.toIso8601String(),
    'basic': basic,
    'allowances': allowances,
    'deductions': deductions,
    'unpaidLeaveDays': unpaidLeaveDays,
    'leaveDeduction': leaveDeduction,
    'status': status.name,
    'paidAt': paidAt?.toIso8601String(),
    'paymentMethod': paymentMethod,
  };

  factory Payslip.fromJson(Map<String, dynamic> j) => Payslip(
    id: j['id'],
    staffId: j['staffId'],
    month: DateTime.parse(j['month']),
    basic: (j['basic'] as num).toDouble(),
    allowances: (j['allowances'] as num).toDouble(),
    deductions: (j['deductions'] as num).toDouble(),
    unpaidLeaveDays: j['unpaidLeaveDays'] ?? 0,
    leaveDeduction: (j['leaveDeduction'] as num?)?.toDouble() ?? 0,
    status: _enumByName(PayslipStatus.values, j['status'], PayslipStatus.draft),
    paidAt: _date(j['paidAt']),
    paymentMethod: j['paymentMethod'] ?? '',
  );
}

